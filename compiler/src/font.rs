/// The font as 96 x 8 bytes, MSB = leftmost pixel.
pub fn bytes() -> Vec<u8> {
    let mut out = Vec::with_capacity(96 * 8);
    for (i, g) in GLYPHS.iter().enumerate() {
        let rows: Vec<&str> = g.split(' ').collect();
        for r in 0..8 {
            let byte = match rows.get(r) {
                // the block glyph fills the whole cell
                Some(row) if i == 95 => {
                    let _ = row;
                    0xFF
                }
                Some(row) => row
                    .bytes()
                    .enumerate()
                    .filter(|&(_, c)| c == b'#')
                    .fold(0u8, |acc, (x, _)| acc | (0x40 >> x)),
                None => 0,
            };
            out.push(byte);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn glyphs_well_formed() {
        for (i, g) in super::GLYPHS.iter().enumerate() {
            let rows: Vec<&str> = g.split(' ').collect();
            assert!(rows.len() == 7 || rows.len() == 8, "glyph {} has {} rows", i + 32, rows.len());
            for r in rows {
                assert_eq!(r.len(), 5, "glyph {} row `{r}`", i + 32);
                assert!(r.bytes().all(|c| c == b'#' || c == b'.'));
            }
        }
        let b = super::bytes();
        assert_eq!(b.len(), 768);
        // 'A' row 0 = .###. -> 0b0011_1000
        assert_eq!(b[(65 - 32) * 8], 0x38);
    }
}
